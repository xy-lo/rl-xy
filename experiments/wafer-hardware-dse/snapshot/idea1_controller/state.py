"""共享真源与生命周期接口。策略无权直接修改以下状态。"""
from typing import Protocol, Sequence
from .contracts import AlgorithmContract, Decision, PreparedBatch, Readiness, RuntimeEvent, TensorSlice, WorldSnapshot, StepPlan, ActionProposal

class WorldState(Protocol):
    def install(self, plan: StepPlan) -> None: ...
    def snapshot(self) -> WorldSnapshot: ...
    def apply_backend_event(self, event: RuntimeEvent) -> WorldSnapshot: ...
    def reserve_decision(self, decision: Decision) -> None: ...
    # 预留与执行完成分开；幂等event_id/command_id用于核对，不宣称容错已实现。

class TaskLedger(Protocol):
    def claim(self, task_id: str, execution_group_id: str, based_on_epoch: int) -> str: ...
    def commit(self, task_id: str, command_id: str, event: RuntimeEvent) -> None: ...
    def all_training_contributions_complete(self, algorithm: AlgorithmContract) -> Readiness: ...

class SampleLedger(Protocol):
    def group_ready(self, group_id: str, region_id: str, snapshot: WorldSnapshot) -> Readiness: ...
    def prepared_batch_ready(self, batch: PreparedBatch, snapshot: WorldSnapshot) -> Readiness: ...
    # EOS不等于送达；送达不等于old/ref/advantage全部准备完成。

class StateCatalog(Protocol):
    def plan_ready(self, plan: StepPlan, snapshot: WorldSnapshot) -> Readiness: ...
    def propose_initialization(self, plan: StepPlan, snapshot: WorldSnapshot) -> Sequence[ActionProposal]: ...
    def require_resident(self, region_id: str, slices: Sequence[TensorSlice], snapshot: WorldSnapshot) -> Readiness: ...
    def admit_transition(self, proposal_id: str, snapshot: WorldSnapshot) -> Readiness: ...
    # actor/reference/optimizer/gradient/KV/activation/NIC/staging共存峰值。

class LeaseManager(Protocol):
    def can_release_region(self, region_id: str, snapshot: WorldSnapshot) -> Readiness: ...
    def can_revoke_at_safe_point(self, lease_id: str, snapshot: WorldSnapshot) -> Readiness: ...


class ResourceManager(Protocol):
    """Read-only resource checks against the authoritative WorldState epoch."""
    def check_action(self, proposal: ActionProposal, snapshot: WorldSnapshot) -> Readiness: ...
    # Reservations are committed through WorldState, never a second occupancy table.
