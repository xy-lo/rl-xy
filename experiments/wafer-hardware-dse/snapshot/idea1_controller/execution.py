"""执行器只执行已批准命令，不自行调度或访问预测不可见的EOS真值。"""
from typing import Protocol, Sequence, Tuple
from .contracts import ActionProposal, CapabilityReport, CommandBatch, Decision, ModelContract, PlacementPlan, RuntimeEvent

class BackendCapabilities(Protocol):
    def validate(self, placement: PlacementPlan, model: ModelContract) -> CapabilityReport: ...
    def supports_action(self, action: ActionProposal) -> CapabilityReport: ...

class CommandExecutor(Protocol):
    def compile(self, decision: Decision) -> CommandBatch: ...
    def submit(self, commands: CommandBatch) -> str: ...
    def poll(self) -> Sequence[RuntimeEvent]: ...

class LegacyT127Adapter(Protocol):
    def describe_capabilities(self) -> CapabilityReport: ...
    # 仅预留接入点：没有实例化、迁移旧逻辑或执行任何程序。
    # 应报告uniform TP2、pending takeover不可用、训练help须全局EOS等限制。
    def translate_approved(self, decision: Decision) -> CommandBatch: ...


class Worker(Protocol):
    """One legal execution group; helper is an action, not a separate worker type."""
    worker_id: str
    die_ids: Tuple[int, ...]
    def execute(self, commands: CommandBatch) -> str: ...
    def poll(self) -> Sequence[RuntimeEvent]: ...
