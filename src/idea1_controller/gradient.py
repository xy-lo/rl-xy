"""异构TP下按参数身份汇总，再进行一次逻辑更新。均为预留接口。"""
from typing import Protocol, Sequence
from .contracts import AlgorithmContract, GradientFragment, GradientRoutePlan, PlacementPlan, Readiness, UpdateTicket, WorldSnapshot

class GradientLayoutPlanner(Protocol):
    def build_route(self, placement: PlacementPlan, algorithm: AlgorithmContract) -> GradientRoutePlan: ...
    # tensor_id+offset为公共坐标，去除TP内复制计数；不按各区域同rank盲目AR。

class GradientCoordinator(Protocol):
    def accept_fragment(self, fragment: GradientFragment) -> None: ...
    def can_finalize(self, snapshot: WorldSnapshot) -> Readiness: ...
    def prepare_update(self, route: GradientRoutePlan, algorithm: AlgorithmContract, snapshot: WorldSnapshot) -> UpdateTicket: ...

class OptimizerCoordinator(Protocol):
    def apply_once(self, ticket: UpdateTicket) -> str: ...
    # owner可分布式并行更新；每个参数分片仅一次，全局clip/normalizer一致。

class WeightPublisher(Protocol):
    def publish_and_reshard(self, ticket: UpdateTicket, target: PlacementPlan) -> str: ...
    def all_target_instances_acknowledged(self, publication_id: str) -> Readiness: ...
